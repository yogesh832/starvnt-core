import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";

// Copy the actual web brand files; never redraw, recolor, or crop them.
const source = new URL("../../web/", import.meta.url);
const target = new URL("../assets/brand/", import.meta.url);
const css = await readFile(new URL("src/theme.css", source), "utf8");
const html = await readFile(new URL("index.html", source), "utf8");
const components = await readFile(
  new URL("src/components/ui.jsx", source),
  "utf8",
);
const theme = css.match(/@theme\s*\{([^}]+)\}/)?.[1] || "";
const token = (name) => {
  const value = theme
    .match(new RegExp(`--color-${name}:\\s*([^;]+);`))?.[1]
    ?.trim();
  if (!value) throw new Error(`Missing web brand token: ${name}`);
  return value;
};
const rule = (selector, property) => {
  const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const value = css
    .match(new RegExp(`${escaped}\\s*\\{([^}]+)\\}`))?.[1]
    .match(new RegExp(`(?:^|[;\\s])${property}:\\s*([^;!}]+)`))?.[1]
    ?.trim();
  if (!value)
    throw new Error(`Missing web brand rule: ${selector} / ${property}`);
  return value;
};
await mkdir(target, { recursive: true });
for (const file of [
  "starvnt-icon.png",
  "starvnt-wordmark.jpg",
  "starvnt-core-logo.jpg",
  "favicon-64.png",
  "apple-touch-icon.png",
]) {
  await copyFile(
    new URL(`public/brand/${file}`, source),
    new URL(file, target),
  );
}
for (const [from, to] of [
  ['images/aura/orb-96.png', 'aura-orb-96.png'],
  ['images/aura/orb-384.png', 'aura-orb-384.png'],
  ['images/aura/orb-motion-128.v1.webp', 'aura-orb-motion-128.v1.webp'],
  ['images/customer-wedding-hero.jpg', 'customer-wedding-hero.jpg'],
]) await copyFile(new URL(`public/${from}`, source), new URL(to, target));
const brand = {
  title: html.match(/<title>([^<]+)<\/title>/)?.[1] || "StarVnt Entertainment",
  // Values are read from the web stylesheet. Generated by npm run sync:brand.
  light: {
    bg: token("lavender"),
    card: "#ffffff",
    ink: token("ink"),
    navy: token("navy"),
    muted: token("muted"),
    line: "#f3f4f6",
    accent: token("primary"),
    accentDark: token("primary-dark"),
    onAccent: "#ffffff",
    soft: token("primary-soft"),
    danger: "#dc2626",
  },
  dark: {
    bg: rule("html.dark body", "background"),
    card: rule("html.dark .bg-white", "background-color"),
    ink: rule("html.dark .text-ink", "color"),
    navy: rule("html.dark .text-navy", "color"),
    muted: rule("html.dark .text-muted", "color"),
    line: rule("html.dark .border-gray-100", "border-color"),
    accent: rule("html.dark .text-primary", "color"),
    accentDark: "#6366f1",
    onAccent: token("navy-deep"),
    soft: rule("html.dark .bg-primary-soft", "background-color"),
    danger: rule("html.dark .text-red-600", "color"),
  },
  wordmarkGradient: [
    token("primary"),
    ...[...components.matchAll(/(?:via|to)-\[(#[\da-f]+)\]/gi)]
      .slice(0, 2)
      .map((match) => match[1]),
  ],
  launchBackground:
    html.match(/name="theme-color" content="([^"]+)"/)?.[1] ||
    token("navy-deep"),
};
await writeFile(
  new URL("../src/brand.generated.json", import.meta.url),
  `${JSON.stringify(brand, null, 2)}\n`,
);
const publicBrand = new URL("../public/brand/", import.meta.url);
await mkdir(publicBrand, { recursive: true });
for (const file of ["favicon-64.png", "apple-touch-icon.png"]) {
  await copyFile(
    new URL(`public/brand/${file}`, source),
    new URL(file, publicBrand),
  );
}
console.log("Mobile brand assets and palette synchronized from web.");

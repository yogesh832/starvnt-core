test('Academy content and resource archives survive withdrawal/edit/retry without reviving vendor access', async () => {
  const author = await admin(), reviewer = await admin(), reader = await admin('ADMIN', ['academy.read']), v = await vendor();
  const initial = { title: 'Archived content fixture', category: 'Getting Started', objective: 'Fixture', content: 'Original text', resources: 'Original resource notes', requestKey: crypto.randomUUID() };
  const created = (await request(app).post('/api/admin/academy').set(author.auth).send(initial).expect(201)).body.lesson;
  const path = `/api/admin/academy/${created.id}`, vendorPath = `/api/vendor/academy/${created.id}`;
  await request(app).post(`${path}/submit-review`).set(author.auth).send({ revision: 1, reason: 'Review original' }).expect(200);
  await request(app).post(`${path}/publication`).set(reviewer.auth).send({ revision: 2, action: 'PUBLISH', reason: 'Approve original', rightsReference: 'fixture-rights' }).expect(200);
  await request(app).put(`${vendorPath}/progress`).set(v.auth).send({ contentVersion: 1, positionSeconds: 0, complete: true }).expect(200);
  await request(app).post(`${path}/publication`).set(reviewer.auth).send({ revision: 3, action: 'WITHDRAW', reason: 'Revise resources' }).expect(200);
  await request(app).get(vendorPath).set(v.auth).expect(404);
  await request(app).post(`${vendorPath}/playback`).set(v.auth).send({}).expect(404);
  const change = { ...initial, revision: 4, content: 'Updated text', resources: 'Updated resources', contentVersions: [] };
  await request(app).put(path).set(author.auth).send(change).expect(200);
  const replay = (await request(app).put(path).set(author.auth).send(change).expect(200)).body.lesson;
  assert.equal(replay.contentVersion, 2); assert.equal(replay.revision, 5);
  const versions = (await request(app).get(`${path}/versions`).set(reader.auth).expect(200)).body;
  assert.equal(versions.currentVersionArchived, true);
  assert.deepEqual(versions.versions.map(row => row.version), [1, 2]);
  assert.equal(versions.versions[0].content.resources, initial.resources);
  assert.equal(versions.versions[1].content.resources, change.resources);
  await request(app).get(`${path}/versions`).set(v.auth).expect(401);
  await request(app).post(`${path}/submit-review`).set(author.auth).send({ revision: 5, reason: 'Review revision' }).expect(200);
  await request(app).post(`${path}/publication`).set(reviewer.auth).send({ revision: 6, action: 'PUBLISH', reason: 'Approve revision', rightsReference: 'fixture-rights-v2' }).expect(200);
  const current = (await request(app).get(vendorPath).set(v.auth).expect(200)).body.lesson;
  assert.equal(current.resources, change.resources); assert.equal(current.contentVersion, 2); assert.equal(current.contentVersions, undefined);
  const catalogue = (await request(app).get('/api/vendor/academy').set(v.auth).expect(200)).body;
  assert.equal(catalogue.lessons.find(row => row.id === created.id).completedAt, null);
  assert.ok((await LearningProgress.findOne({ vendor: v.organization._id, lesson: created.id, contentVersion: 1 })).completedAt);
  assert.equal((await LearningLesson.findById(created.id)).history.at(-1).contentHash, versions.versions[1].hash);
});
